CREATE TABLE IF NOT EXISTS runtime.task_drone_candidates (
  candidate_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id bigint NOT NULL REFERENCES runtime.tasks(task_id) ON DELETE CASCADE,
  route_id bigint REFERENCES runtime.routes(route_id) ON DELETE CASCADE,
  drone_id bigint NOT NULL REFERENCES runtime.drones(drone_id) ON DELETE CASCADE,
  recommendation_rank integer,
  is_eligible boolean NOT NULL,
  is_recommended boolean NOT NULL DEFAULT false,
  task_distance_km numeric,
  available_range_km numeric,
  battery_percent numeric,
  safety_factor numeric NOT NULL DEFAULT 0.7,
  payload_passed boolean NOT NULL,
  range_passed boolean NOT NULL,
  battery_passed boolean NOT NULL,
  status_passed boolean NOT NULL,
  capability_passed boolean NOT NULL,
  matched_capabilities jsonb NOT NULL DEFAULT '[]'::jsonb,
  missing_capabilities jsonb NOT NULL DEFAULT '[]'::jsonb,
  rejection_reasons jsonb NOT NULL DEFAULT '[]'::jsonb,
  recommendation_reason text,
  evaluated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (task_id, route_id, drone_id)
);

CREATE INDEX IF NOT EXISTS idx_task_drone_candidates_task_rank
  ON runtime.task_drone_candidates(task_id, recommendation_rank, candidate_id);

