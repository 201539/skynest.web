-- The survey does not establish built-in cargo protection for most models.
-- Record accessories/unknown explicitly instead of inventing support.
INSERT INTO static.drone_model_capabilities (model_id, capability_code, support_status, support_method, evidence_source)
SELECT m.model_id, c.capability_code,
  CASE
    WHEN c.capability_code = 'low_noise' AND m.model_code = 'FP400V4' THEN 'supported'
    WHEN c.capability_code IN ('shockproof','waterproof','leakproof','cold_chain','temperature_controlled') THEN 'requires_accessory'
    ELSE 'unknown'
  END,
  CASE
    WHEN c.capability_code = 'low_noise' AND m.model_code = 'FP400V4' THEN '静音桨，调研资料称噪音较上代下降50%'
    WHEN c.capability_code IN ('shockproof','waterproof','leakproof','cold_chain','temperature_controlled') THEN '需由运营端确认对应货箱或包装配置'
    ELSE '调研资料未披露'
  END,
  '行业调研(1).docx'
FROM static.drone_models m CROSS JOIN static.transport_capabilities c
ON CONFLICT (model_id, capability_code) DO UPDATE SET
  support_status=EXCLUDED.support_status,
  support_method=EXCLUDED.support_method,
  evidence_source=EXCLUDED.evidence_source;

