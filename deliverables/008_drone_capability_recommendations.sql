-- Static facts shared by every physical drone of the same model.
CREATE TABLE IF NOT EXISTS static.drone_models (
  model_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model_code text UNIQUE NOT NULL,
  model_name text NOT NULL,
  manufacturer text,
  vehicle_class text NOT NULL,
  max_payload_kg numeric,
  nominal_range_km numeric,
  range_definition text,
  max_wind_mps numeric,
  wind_level_text text,
  positioning_accuracy text,
  noise_description text,
  takeoff_modes jsonb NOT NULL DEFAULT '[]'::jsonb,
  interface_type text,
  source_date date,
  source_note text,
  remarks text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS static.transport_capabilities (
  capability_code text PRIMARY KEY,
  capability_name text UNIQUE NOT NULL,
  description text
);

CREATE TABLE IF NOT EXISTS static.drone_model_capabilities (
  model_id bigint NOT NULL REFERENCES static.drone_models(model_id) ON DELETE CASCADE,
  capability_code text NOT NULL REFERENCES static.transport_capabilities(capability_code),
  support_status text NOT NULL CHECK (support_status IN ('supported', 'not_supported', 'requires_accessory', 'unknown')),
  support_method text,
  evidence_source text,
  verified_at date,
  PRIMARY KEY (model_id, capability_code)
);

